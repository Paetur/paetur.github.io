const fs = require('node:fs');
const assert = require('node:assert/strict');
const categories = ['interface', 'food', 'types'];
function flatten(value, prefix = '', result = {}) {
 assert.ok(value && typeof value === 'object' && !Array.isArray(value), 'Catalog must contain objects and strings');
 for (const [key, child] of Object.entries(value)) {
  assert.ok(!key.includes('.') && !['__proto__','constructor','prototype'].includes(key), 'Invalid key '+key);
  const path = prefix ? prefix+'.'+key : key;
  if (typeof child === 'string') result[path] = child;
  else flatten(child, path, result);
 }
 return result;
}
const tokens = text => [...text.matchAll(/\{([A-Za-z][A-Za-z0-9_]*)\}/g)].map(match=>match[1]).sort();
const read = (lang, category) => flatten(JSON.parse(fs.readFileSync(`locales/${lang}/${category}.json`, 'utf8')));
const english = Object.fromEntries(categories.map(category=>[category,read('en',category)]));
for (const entry of fs.readdirSync('locales', {withFileTypes:true}).filter(entry=>entry.isDirectory())) {
 for (const category of categories) {
  const values = read(entry.name, category);
  assert.deepEqual(Object.keys(values).sort(), Object.keys(english[category]).sort(), `${entry.name}/${category} keys`);
  for (const [key, source] of Object.entries(english[category])) {
   assert.ok(source.trim(), `Empty English source ${category}.${key}`);
   if (values[key].trim()) assert.deepEqual(tokens(values[key]),tokens(source), `${entry.name}/${category}.${key} placeholders`);
  }
 }
}
const aliases = JSON.parse(fs.readFileSync('locales/aliases.json','utf8'));
for (const [source, path] of Object.entries(aliases)) {
 const [category,...parts] = path.split('.');
 assert.equal(english[category]?.[parts.join('.')],source,'Invalid alias '+path);
}
for (const file of fs.readdirSync('js').filter(file=>file.endsWith('.js'))) {
 const code = fs.readFileSync('js/'+file,'utf8');
 for (const match of code.matchAll(/["']((interface|food|types)\.(messages|units)\.[a-z0-9_]+)["']/g)) {
  const [category,...parts] = match[1].split('.');
  assert.ok(Object.hasOwn(english[category],parts.join('.')),file+' unknown translation key '+match[1]);
 }
}
const manifest = '// Generated by tools/validate-locales.cjs --generate. Edit locales JSON.\nwindow.RSVP_TRANSLATIONS = '+JSON.stringify(Object.fromEntries(Object.entries(aliases).map(([source,key])=>[source,{key}])),null,2)+';\n';
if (process.argv.includes('--generate')) fs.writeFileSync('js/translations.js',manifest);
else assert.equal(fs.readFileSync('js/translations.js','utf8'),manifest,'Regenerate compatibility manifest');
console.log('PASS locale JSON, key parity, English sources, placeholders and compatibility manifest');
